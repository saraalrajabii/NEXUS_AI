"""The database itself enforces "no duplicates" — not just our Python code."""

import pytest
from sqlalchemy.exc import IntegrityError

from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from tests.conftest import alembic_config, make_test_settings
from tests.factories import make_conversation, make_event, make_message


def test_duplicate_webhook_delivery_is_rejected(db):
    make_event(db, "delivery-123")
    with pytest.raises(IntegrityError, match="uq_webhook_events_source_delivery_id"):
        make_event(db, "delivery-123")


def test_duplicate_external_message_is_rejected(db):
    c = make_conversation(db)
    make_message(db, c, "chatwoot-msg-7", "hello")
    with pytest.raises(IntegrityError, match="uq_messages_source_external_id"):
        make_message(db, c, "chatwoot-msg-7", "hello again")


def test_duplicate_external_conversation_is_rejected(db):
    make_conversation(db, "99")
    with pytest.raises(IntegrityError, match="uq_conversations_source_external_account_id_external_id"):
        make_conversation(db, "99")


def test_invalid_status_is_rejected(db):
    with pytest.raises(IntegrityError, match="ck_conversations_status_valid"):
        make_conversation(db, "1", status="banana")


def test_models_match_migrations(engine):
    """Fails if someone changes a model without writing a migration."""
    url = make_test_settings().database_url().render_as_string(hide_password=False)
    try:
        command.check(alembic_config(url))
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - only on failure
        pytest.fail(f"Models and migrations differ: {exc}")
